let currentLang = 'en';

document.addEventListener('DOMContentLoaded', () => {
    // 1. Ambient Background Particle Canvas
    initCanvas();

    // 2. Language Switcher Initialization
    initLanguageToggle();

    // 3. Interactive Cursor-Driven 5-Element Transition
    initHeroElementTransition();

    // 4. Glass Bubble Buttons Click Handlers & Smooth Scroll
    initGlassBubbleButtons();
});

// Language Switcher Logic
function initLanguageToggle() {
    const btnToggle = document.getElementById('btn-lang-toggle');
    const langText = document.getElementById('lang-current');

    if (!btnToggle) return;

    btnToggle.addEventListener('click', () => {
        currentLang = currentLang === 'en' ? 'ar' : 'en';
        setLanguage(currentLang);
    });
}

function setLanguage(lang) {
    currentLang = lang;
    const body = document.body;
    const langText = document.getElementById('lang-current');

    if (lang === 'ar') {
        body.classList.add('lang-ar');
        body.classList.remove('lang-en');
        body.setAttribute('dir', 'rtl');
        if (langText) langText.textContent = 'English';
    } else {
        body.classList.add('lang-en');
        body.classList.remove('lang-ar');
        body.setAttribute('dir', 'ltr');
        if (langText) langText.textContent = 'العربية';
    }

    // Update all data-i18n elements
    const i18nElements = document.querySelectorAll('[data-i18n]');
    i18nElements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });
}

// Canvas Particles
function initCanvas() {
    const canvas = document.getElementById('bg-canvas');
    if (!canvas) return;
    const ctx = canvas.getContext('2d');

    let width = canvas.width = window.innerWidth;
    let height = canvas.height = window.innerHeight;

    window.addEventListener('resize', () => {
        width = canvas.width = window.innerWidth;
        height = canvas.height = window.innerHeight;
    });

    const particles = [];
    const count = 40;

    for (let i = 0; i < count; i++) {
        particles.push({
            x: Math.random() * width,
            y: Math.random() * height,
            radius: Math.random() * 2 + 1,
            vx: (Math.random() - 0.5) * 0.4,
            vy: (Math.random() - 0.5) * 0.4,
            alpha: Math.random() * 0.4 + 0.2
        });
    }

    function animate() {
        ctx.clearRect(0, 0, width, height);

        particles.forEach(p => {
            p.x += p.vx;
            p.y += p.vy;

            if (p.x < 0) p.x = width;
            if (p.x > width) p.x = 0;
            if (p.y < 0) p.y = height;
            if (p.y > height) p.y = 0;

            ctx.beginPath();
            ctx.arc(p.x, p.y, p.radius, 0, Math.PI * 2);
            ctx.fillStyle = `rgba(59, 168, 159, ${p.alpha})`;
            ctx.fill();
        });

        requestAnimationFrame(animate);
    }

    animate();
}

// Interactive 5-Element Transition with Mouse tracking, Click Cycle, and Auto-Rotation
function initHeroElementTransition() {
    const images = [
        document.getElementById('hero-img-1'), // Helper / Technician
        document.getElementById('hero-img-2'), // Barber
        document.getElementById('hero-img-3'), // Driver
        document.getElementById('hero-img-4'), // Electrician
        document.getElementById('hero-img-5')  // Tailor
    ].filter(Boolean);

    const wrapper = document.getElementById('hero-center-wrapper');
    const roleTitleEl = document.getElementById('active-role-title');

    if (images.length === 0) return;

    let activeIndex = 0;
    let autoRotateTimer = null;

    function activateElement(index) {
        if (index < 0 || index >= images.length) return;
        activeIndex = index;
        images.forEach((img, idx) => {
            if (idx === activeIndex) {
                img.classList.add('active');
            } else {
                img.classList.remove('active');
            }
        });

        // Update Dynamic Hero Role Badge
        if (roleTitleEl) {
            const roleKey = `role_${activeIndex + 1}`;
            roleTitleEl.setAttribute('data-i18n', roleKey);
            if (translations[currentLang] && translations[currentLang][roleKey]) {
                roleTitleEl.textContent = translations[currentLang][roleKey];
            }
        }
    }

    function resetAutoRotate() {
        if (autoRotateTimer) clearInterval(autoRotateTimer);
        autoRotateTimer = setInterval(() => {
            const nextIdx = (activeIndex + 1) % images.length;
            activateElement(nextIdx);
        }, 4000);
    }

    // Mouse Move Transition across 5 horizontal zones
    window.addEventListener('mousemove', (e) => {
        const mouseX = e.clientX;
        const screenWidth = window.innerWidth;

        const zoneRatio = mouseX / screenWidth;
        let newIndex = Math.floor(zoneRatio * images.length);
        if (newIndex >= images.length) newIndex = images.length - 1;

        if (newIndex !== activeIndex) {
            activateElement(newIndex);
            resetAutoRotate();
        }

        // 3D parallax tilt effect following cursor movement
        if (wrapper) {
            const tiltX = (e.clientY / window.innerHeight - 0.5) * -6;
            const tiltY = (e.clientX / window.innerWidth - 0.5) * 10;
            wrapper.style.transform = `translateX(-48%) rotateX(${tiltX}deg) rotateY(${tiltY}deg)`;
        }
    });

    // Click to cycle manually
    if (wrapper) {
        wrapper.addEventListener('click', () => {
            const nextIdx = (activeIndex + 1) % images.length;
            activateElement(nextIdx);
            resetAutoRotate();
        });
    }

    // Start initial auto rotation
    resetAutoRotate();
}

// Glass Bubble Buttons Handler
function initGlassBubbleButtons() {
    const btnHeaderProcess = document.getElementById('btn-glass-info');

    if (btnHeaderProcess) {
        btnHeaderProcess.addEventListener('click', (e) => {
            e.preventDefault();
            const procSec = document.getElementById('process');
            if (procSec) {
                procSec.scrollIntoView({ behavior: 'smooth' });
            }
        });
    }
}
